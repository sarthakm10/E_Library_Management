package com.elibrary.db;

import jakarta.annotation.PostConstruct;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.jdbc.core.ConnectionCallback;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * Adds the tables and columns that renewals, holds, fines and borrowing history need, on any of the
 * supported databases (MySQL, SQL Server, H2). Runs at startup before the API serves requests, and only
 * touches what's missing, so it's safe on every start and on the original legacy elibraryDB.
 */
@Component
public class SchemaUpgrader {
    private static final Logger log = LoggerFactory.getLogger(SchemaUpgrader.class);

    private final JdbcTemplate jdbc;

    public SchemaUpgrader(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    private enum Dialect { MYSQL, SQLSERVER, H2 }

    @PostConstruct
    public void upgrade() {
        Dialect d = dialect();
        String text = d == Dialect.SQLSERVER ? "NVARCHAR" : "VARCHAR";
        String autoId = switch (d) {
            case MYSQL -> "BIGINT AUTO_INCREMENT PRIMARY KEY";
            case SQLSERVER -> "BIGINT IDENTITY(1,1) PRIMARY KEY";
            case H2 -> "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
        };

        // How many times each open loan has been renewed.
        if (!columnExists("book_issue_tbl", "renew_count")) {
            run("ALTER TABLE book_issue_tbl ADD renew_count INT DEFAULT 0 NOT NULL", "book_issue_tbl.renew_count");
        }

        // One row per returned loan. Fines live here: fine_amount is set at return time; fine_paid is 0/1.
        if (!tableExists("loan_history_tbl")) {
            run("""
                    CREATE TABLE loan_history_tbl (
                        history_id  %2$s,
                        member_id   %1$s(50) NOT NULL,
                        member_name %1$s(100),
                        book_id     %1$s(50) NOT NULL,
                        book_name   %1$s(300),
                        issue_date  %1$s(20),
                        due_date    %1$s(20),
                        return_date %1$s(20),
                        renew_count INT DEFAULT 0 NOT NULL,
                        fine_amount INT DEFAULT 0 NOT NULL,
                        fine_paid   INT DEFAULT 0 NOT NULL
                    )""".formatted(text, autoId), "loan_history_tbl");
        }

        // Queue of members waiting for a book. status: 'waiting' or 'ready' (a copy is kept aside until ready_until).
        if (!tableExists("book_hold_tbl")) {
            run("""
                    CREATE TABLE book_hold_tbl (
                        member_id   %1$s(50) NOT NULL,
                        member_name %1$s(100),
                        book_id     %1$s(50) NOT NULL,
                        book_name   %1$s(300),
                        placed_at   %1$s(30) NOT NULL,
                        status      %1$s(20) NOT NULL,
                        ready_until %1$s(20),
                        PRIMARY KEY (member_id, book_id)
                    )""".formatted(text), "book_hold_tbl");
        }
    }

    private Dialect dialect() {
        String product = jdbc.execute((ConnectionCallback<String>) c -> c.getMetaData().getDatabaseProductName());
        if (product == null) return Dialect.MYSQL;
        String p = product.toLowerCase();
        if (p.contains("microsoft") || p.contains("sql server")) return Dialect.SQLSERVER;
        if (p.contains("h2")) return Dialect.H2;
        return Dialect.MYSQL;
    }

    // A failing probe query is the most portable "does it exist" check across the three databases.
    private boolean tableExists(String table) {
        try {
            jdbc.queryForObject("SELECT COUNT(*) FROM " + table + " WHERE 1 = 0", Integer.class);
            return true;
        } catch (Exception e) {
            return false;
        }
    }

    private boolean columnExists(String table, String column) {
        try {
            jdbc.queryForList("SELECT " + column + " FROM " + table + " WHERE 1 = 0");
            return true;
        } catch (Exception e) {
            return false;
        }
    }

    private void run(String ddl, String what) {
        jdbc.execute(ddl);
        log.info("Database upgraded: added {}", what);
    }
}
